-- 014 · 素材审核：驳回理由
--
-- ---------------------------------------------------------------- 为什么要这个字段
--
-- 011 建表时留了 ``review_status`` / ``reviewer_id`` / ``reviewed_at``，
-- 但**没有地方写驳回的原因**。而"驳回"如果不说为什么，对生成方来说
-- 等价于"再随便试一次"——素材是模型生成的，不告诉它哪里不对，
-- 下一版大概率还是同样的毛病。
--
-- 更要紧的是这条链的后半截：驳回理由是**回流数据**。哪类提示词老被驳、
-- 驳在哪一点上，是运营 Agent 该学的东西（docs/10 的风格样本正是这么攒的）。
-- 只存一个 rejected 状态，这部分信息就永远丢了。
--
-- ---------------------------------------------------------------- 为什么通过也允许写
--
-- 不强制，但允许。"这张可以，但下次别再把模特手放这么高"这种话，
-- 现在没有别的地方可放。
--
-- 执行：mysql -u root -p smartmall < deploy/sql/migrations/014_asset_review.sql

ALTER TABLE `marketing_asset`
  ADD COLUMN `review_note` VARCHAR(256) NOT NULL DEFAULT ''
    COMMENT '审核意见。驳回时必填——不写原因的驳回，生成方不知道该改什么'
    AFTER `review_status`;
