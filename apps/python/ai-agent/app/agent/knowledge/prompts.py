DRAFT_USER = """有个用户问了这个问题，客服没答上来。请根据下面的依据写一条
知识库条目，让以后遇到同样的问题能直接回答。

问题：{question}
{variants_hint}
可用依据（**只能用这里面的信息**）：
{evidence}

要求：

- 直接写答案本身，不要"您好""希望能帮到您"这类客套
- 只写依据里有的东西。**依据里没提到的一律不写**——
  不确定的地方少写一句，比写一句听起来合理但没出处的强
- **一个数字都不能编。** 天数、温度、百分比、价格、尺码，
  凡是依据里没出现过的数字都不许写。这条会被程序逐个核对
- 两到四句话，陈述语气，像一条资料而不是一段对话

**如果依据不够写出这条知识，就只输出四个字：材料不足。**
这不是失败——编一条听起来合理的知识写进库里，之后每个问到这件事的
用户都会拿到它，那比暂时没有答案糟糕得多。"""


