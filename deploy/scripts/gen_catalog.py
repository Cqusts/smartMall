def esc(s: str) -> str:
    return str(s).replace("\\", "\\\\").replace("'", "''")


def build() -> tuple[list[str], list[str], list[str], list[str], dict]:
    rnd = random.Random(SEED)
    cats: dict[int, tuple] = {}
    products: list[str] = []
    attrs: list[str] = []
    skus: list[str] = []
    charts: list[str] = []
    stats: dict[str, int] = {}

    pid = 10001
    used_names: set[str] = set()

    for l1_id, l1, l2_id, l2, l3_id, l3, kind, prefixes, cores, lo, hi in TREE:
        cats[l1_id] = (l1_id, 0, l1, 1, f"/{l1_id}")
        cats[l2_id] = (l2_id, l1_id, l2, 2, f"/{l1_id}/{l2_id}")
        cats[l3_id] = (l3_id, l2_id, l3, 3, f"/{l1_id}/{l2_id}/{l3_id}")
        schema = KINDS[kind]
        stats[kind] = stats.get(kind, 0) + PER_L3

        for i in range(PER_L3):
            # 名字：修饰 + 核心。撞名就换一个修饰词——库里两个同名商品
            # 会让"用户问的是哪一件"永远说不清
            tails = TAILS[kind]
            for attempt in range(80):
                pre = prefixes[(i + attempt) % len(prefixes)]
                core = cores[(i + attempt // len(prefixes)) % len(cores)]
                tail = tails[(i + attempt // 3) % len(tails)]
                name = f"{pre}{core} {tail}".strip()
                if name and name not in used_names:
                    break
            else:  # pragma: no cover
                name = f"{l3}{i + 1}"
            used_names.add(name)

            price = round(rnd.uniform(lo, hi), 0)
            # 四成商品有划线价。**全场都打折等于没打折**，而且真实店铺
            # 里长期挂着原价的商品占多数
